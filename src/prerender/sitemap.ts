/**
 * The sitemap written to dist/sitemap.xml by the build (scripts/prerender.mjs),
 * from the same pages the prerender writes (K-019). Pure, so it is unit tested
 * (sitemap.test.ts).
 *
 * Each <loc> is the page's own canonical URL, as read from its rendered head,
 * so the sitemap and the canonicals cannot disagree about a trailing slash.
 * Pages marked noindex are left out by the caller.
 */

export type SitemapEntry = { loc: string; lastmod: string }

const escapeXml = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;")

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/

export function buildSitemap(entries: SitemapEntry[]): string {
  const locs = new Set<string>()
  for (const e of entries) {
    if (!/^https:\/\/gakinz\.com\//.test(e.loc)) throw new Error(`sitemap: ${e.loc} is not an absolute https://gakinz.com URL`)
    if (!ISO_DATE.test(e.lastmod)) throw new Error(`sitemap: ${e.loc} has lastmod "${e.lastmod}", expected YYYY-MM-DD`)
    if (locs.has(e.loc)) throw new Error(`sitemap: ${e.loc} is listed twice`)
    locs.add(e.loc)
  }
  const urls = entries.map(
    (e) => `  <url>\n    <loc>${escapeXml(e.loc)}</loc>\n    <lastmod>${e.lastmod}</lastmod>\n  </url>`,
  )
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    "<!-- Generated by npm run build (scripts/prerender.mjs). Do not edit. -->",
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...urls,
    "</urlset>",
    "",
  ].join("\n")
}
